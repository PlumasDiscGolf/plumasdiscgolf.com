<div class="mt-16 w-full">
	<h2 class="mx-auto mb-6 text-center text-3xl font-bold">Comprehensive Rules</h2>
	<div class="prose lg:prose-xl mx-auto max-w-[75ch]">
		<p>These rules govern the operation of Plumas Disc Golf as a club, unless otherwise specified.</p>
		<ol>
			<li>
				<strong>Membership</strong>
				<ol>
					<li>Membership in Plumas Disc Golf is open to any individual who pays the applicable annual membership fee.</li>
					<li>Membership is valid for the calendar year in which it is purchased and expires December 31st of that year, unless renewed.</li>
					<li>Membership renewal is enabled by default (auto-renewal) but may be turned off or canceled by the member at any time.</li>
					<li>Membership tiers are described on the <a href="/membership">Membership</a> page, with benefits subject to change at the discretion of the Board.</li>
					<li>Membership does not guarantee entry into any specific event; some events may have additional registration requirements or capacity limits.</li>
				</ol>
			</li>
			<li>
				<strong>Governance / Officers</strong>
				<ol>
					<li>Plumas Disc Golf is governed by a Board of Officers, consisting of the following positions, in order of precedence: President, Vice President, Secretary, Treasurer, and Officer(s) at Large.</li>
					<li><strong>President:</strong> Oversees overall club operations, presides over Board meetings, and serves as the primary point of contact for club matters.</li>
					<li><strong>Vice President:</strong> Assists the President and assumes President responsibilities in their absence.</li>
					<li><strong>Secretary:</strong> Maintains records of Board meetings, membership, and club correspondence.</li>
					<li><strong>Treasurer:</strong> Manages club finances, including dues, event proceeds, and expenditures.</li>
					<li><strong>Officer(s) at Large:</strong> Support the Board with league management, event coordination, and other duties as assigned.</li>
					<li><strong>Term:</strong> Officers serve a term of two (2) years, after which the position is subject to re-election by the Board.</li>
					<li><strong>Selection:</strong> Officers are elected by the existing Board of Officers.</li>
					<li>In the absence of the President and Vice President, rules disputes or decisions requiring officer authority will be handled by the highest-ranking officer present, per the order in 2.1.</li>
				</ol>
			</li>
			<li>
				<strong>Elections</strong>
				<ol>
					<li>Elections for open or expiring Officer positions will be held by a vote of the current Board of Officers.</li>
					<li>A quorum of a majority of Officers must participate for a vote to be valid.</li>
					<li>Elections are decided by a simple majority of the votes cast.</li>
					<li>Officers may serve consecutive terms if re-elected by the Board.</li>
					<li>In the event an Officer position becomes vacant mid-term (resignation, removal, etc.), the Board will hold a vote, under the same quorum and majority requirements, to appoint a replacement to serve the remainder of the term.</li>
				</ol>
			</li>
			<li>
				<strong>Board Meetings</strong>
				<ol>
					<li>The Board will hold regular meetings to conduct club business, review finances, and plan events.</li>
					<li>Board meetings are planned to occur quarterly, with a minimum of one (1) meeting required per year.</li>
					<li>Meeting agendas and minutes will be recorded by the Secretary and published on the Plumas Disc Golf website.</li>
					<li>Special meetings may be called by the President, or by a majority of the Board, as needed.</li>
				</ol>
			</li>
			<li>
				<strong>Committees</strong>
				<ol>
					<li>The Board may form committees as needed to address specific club matters.</li>
					<li>Committee composition and size are determined by the Board on an as-needed basis and are not fixed.</li>
					<li>Committee members are appointed by the Board and may include current Officers and/or general members in good standing.</li>
				</ol>
			</li>
			<li>
				<strong>Dues &amp; Fees</strong>
				<ol>
					<li>Annual membership dues are set by the Board and are subject to change from year to year.</li>
					<li>Changes to membership dues are decided by a Board vote, under the same quorum and simple majority requirements described in Section 3.</li>
					<li>Current membership dues and tiers are listed on the <a href="/membership">Membership</a> page.</li>
					<li>Event-specific fees (e.g., league or tournament entry fees) may apply in addition to membership dues, as described on each event's page.</li>
					<li>Membership dues are non-refundable, including in cases where a member cancels their membership partway through the year.</li>
					<li>Any changes to membership dues will be published on the Plumas Disc Golf website in advance of the following membership year.</li>
				</ol>
			</li>
			<li>
				<strong>Conduct and Etiquette</strong>
				<ol>
					<li>All members and participants are expected to adhere to the <a href="https://www.pdga.com/rules/competition-manual/section-3" target="_blank" rel="noopener noreferrer">PDGA Code of Conduct</a> (Section 3 of the PDGA Competition Manual) and demonstrate good sportsmanship at club events and courses. Players may also reference the <a href="https://www.pdga.com/code" target="_blank" rel="noopener noreferrer">Disc Golfer's Code</a> as a simplified, plain-language companion to the Code of Conduct.</li>
					<li>Members are expected to treat other players, volunteers, officers, and course staff with respect.</li>
					<li>All events run by Plumas Disc Golf will adhere to PDGA rules of play, regardless of whether the event is PDGA-sanctioned, unless otherwise specified in that event's own rules.</li>
				</ol>
			</li>
			<li>
				<strong>Rules Disputes</strong>
				<ol>
					<li>Rules disputes at club events will be handled by that event's Event Coordinator.</li>
					<li>The Event Coordinator may take the form of a League Director, Tournament Director, Assistant Tournament Director, or other official, as designated for that specific event.</li>
				</ol>
			</li>
			<li>
				<strong>Disciplinary Process / Disqualification</strong>
				<ol>
					<li>Violations of these rules, event-specific rules, or the PDGA Code of Conduct may result in disqualification from an event, at the discretion of that event's Event Coordinator.</li>
					<li>Repeated or serious violations may be escalated to the Disciplinary Committee for review.</li>
					<li>The Disciplinary Committee may impose consequences up to and including revocation of membership.</li>
				</ol>
			</li>
			<li>
				<strong>Amendments to These Rules</strong>
				<ol>
					<li>These rules may be amended by a vote of the Board of Officers, under the same quorum and simple majority requirements described in Section 3.</li>
					<li>Amendments take effect immediately upon approval, unless otherwise specified by the Board.</li>
					<li>The current version of these rules will always be published on the Plumas Disc Golf website.</li>
				</ol>
			</li>
			<li>
				<strong>Agreement to the Rules</strong>
				<ol>
					<li>By becoming a member of, or participating in any event hosted by, Plumas Disc Golf, all members and participants agree to abide by these club rules.</li>
				</ol>
			</li>
		</ol>
	</div>
</div>

