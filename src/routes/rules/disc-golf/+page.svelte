		<h2>New to Disc Golf?</h2>
		<p>
			Disc golf is easy to pick up and a lot of fun to play. The basic idea is a lot like traditional golf, except you're throwing a flying disc at a target instead of hitting a ball with a club. Below is a quick rundown of the essentials to get you comfortable on the course. For the full, official ruleset, check out the <a href="https://www.pdga.com/rules" target="_blank" rel="noopener noreferrer">PDGA Official Rules of Disc Golf</a>.
		</p>

		<h2>Safety First</h2>
		<p>
			Before anything else: never throw when someone is within range, whether that's another player, a hiker, or anyone else in the area. Always yield the right of way to others, and stay aware of what's happening around you at all times.
		</p>

		<h2>Objective of the Game</h2>
		<p>
			Each hole starts at a tee and ends at a basket. Every time you throw your disc, or pick up a penalty, that's one stroke. The goal on each hole is to get your disc into the basket in as few strokes as possible. A hole is finished once your disc comes to rest in the basket or is caught in the chains. After playing every hole on the course, the player with the lowest total stroke count wins.
		</p>

		<h2>Tee Throws</h2>
		<p>
			Every hole begins with a tee throw, which must be thrown from within or behind the marked tee area.
		</p>

		<h2>Fairway Throws</h2>
		<p>
			Once you're off the tee, each throw is made from directly behind your lie (see below). You're allowed a run-up and a normal follow-through after release — unless your lie is within about 10 meters of the basket. Inside that range, you'll need to keep your balance and stay put until			your disc comes to a complete stop.
		</p>

		<h2>Out of Bounds</h2>
		<p>
			If the entirety of your disc is outside of the marked OB line, your disc is out of bounds. When that happens, play continues from a point up to 1 meter in bounds from where the disc crossed the line. Keep an eye out for common out-of-bounds areas like ponds, roads, and the edges of the course itself.
		</p>

		<h2>Mandatories</h2>
		<p>
			Some holes include a "mando" — one or more designated trees or poles that your disc must pass on a specific side, usually marked with an arrow. If your disc passes the wrong side of a mando, you'll need to replay the throw from your previous lie (or a marked drop zone, if one is provided), and add a one-throw penalty.
		</p>

		<h2>Throwing Order</h2>
		<p>
			On the tee, whoever had the fewest strokes on the previous hole throws first. Once everyone has teed off, it's always the player whose disc is farthest from the basket who throws next.
		</p>

		<h2>Your Lie</h2>
		<p>
			Your lie is simply where your last throw came to rest. Mark it with a mini marker disc, or just leave your thrown disc where it landed, and	make your next throw from directly behind it.
		</p>

		<h2>Course Etiquette</h2>
		<ul>
			<li>Stay quiet and avoid unnecessary movement while someone else is throwing.</li>
			<li>Stand behind the player who's throwing until they've finished their throw.</li>
			<li>Remove your disc from the basket once you've finished the hole.</li>
			<li>Help newer players learn the ropes when you can.</li>
			<li>Let faster groups play through when it makes sense.</li>
			<li>Pack out your trash, and any trash you find along the way.</li>
			<li>Leave the course as you found it — don't alter trees, bushes, or other natural features.</li>
		</ul>

